def ft_harvest_total():
    day1 = input("harvest day1: ")
    day2 = input("harvest day2: ")
    day3 = input("harvest day3: ")
    print("Day 1 harvest: ", day1)
    print("Day 2 harvest: ", day2)
    print("Day 3 harvest: ", day3)
    print("Total Day Harvest: ", day1 + day2 + day3)

def main():
    ft_harvest_total()

